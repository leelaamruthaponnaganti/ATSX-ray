import { NextResponse, type NextRequest } from "next/server";
import { analyzeResume } from "@/lib/analysis";
import { EXPERIENCE_LEVELS, LIMITS } from "@/lib/constants";
import { llmTailor } from "@/lib/enhancement/llm";
import { tailorResume } from "@/lib/enhancement/tailor";
import { AnalysisRequestError } from "@/lib/parsing/validateFile";
import { filterJunkSkills } from "@/lib/text/synonyms";
import type { EnhanceRequest, EnhanceResponse, ExperienceLevel } from "@/lib/types";

export const runtime = "nodejs";
export const maxDuration = 60;

function asString(value: unknown): string {
  return typeof value === "string" ? value.trim() : "";
}

function fail(code: string, message: string, status: number): never {
  throw new AnalysisRequestError(code, message, status);
}

export async function POST(request: NextRequest) {
  try {
    const body = (await request.json()) as Record<string, unknown>;
    const resumeText = asString(body.resumeText);
    const jobDescription = asString(body.jobDescription);
    const targetRole = asString(body.targetRole);
    const targetCompany = asString(body.targetCompany);
    const experienceLevel = asString(body.experienceLevel) as ExperienceLevel;
    const missingKeywords = Array.isArray(body.missingKeywords)
      ? filterJunkSkills(
          body.missingKeywords
            .filter((item): item is string => typeof item === "string" && item.trim().length > 0)
            .map((item) => item.trim()),
        ).slice(0, 20)
      : [];

    if (resumeText.length < LIMITS.minResumeChars) {
      fail("RESUME_TOO_SHORT", "Analyze a resume first so the enhancer has real extracted text to work with.", 400);
    }
    if (jobDescription.length < LIMITS.minJobDescriptionChars) {
      fail("JD_TOO_SHORT", "A job description with at least 40 characters is required for tailoring.", 400);
    }
    if (targetRole.length < 2 || targetRole.length > 120) {
      fail("INVALID_ROLE", "Enter a target role between 2 and 120 characters.", 400);
    }
    if (targetCompany.length < 1 || targetCompany.length > 120) {
      fail("INVALID_COMPANY", "Enter a target company name (up to 120 characters).", 400);
    }
    if (!EXPERIENCE_LEVELS.includes(experienceLevel)) {
      fail("INVALID_LEVEL", "Choose Fresher / Graduate, 1–3 Years, or 3+ Years.", 400);
    }

    const input: EnhanceRequest = {
      resumeText,
      jobDescription,
      targetRole,
      targetCompany,
      experienceLevel,
      missingKeywords,
    };

    const computedBefore = analyzeResume({
      resumeText,
      rawText: resumeText,
      jobDescription,
      fileName: "Original resume",
      fileType: "text",
    }).score;
    const providedBefore =
      typeof body.beforeScore === "number" && Number.isFinite(body.beforeScore)
        ? Math.min(100, Math.max(0, Math.round(body.beforeScore)))
        : computedBefore;

    const template = tailorResume(input);
    const boosted = await llmTailor(input);
    const tailored = boosted ?? { ...template, engine: "template" as const };

    const projected = analyzeResume({
      resumeText: tailored.enhancedText,
      rawText: tailored.enhancedText,
      jobDescription,
      fileName: "Tailored resume",
      fileType: "text",
    });

    const warnings: string[] = [];
    if (missingKeywords.length > 0 && tailored.keywordsWoven.length === 0) {
      warnings.push("No new keywords were injected because every supplied term was either generic or already present. Verify your skills section before submission.");
    }
    if (/\[quantify|\[add |\[insert/i.test(tailored.enhancedText)) {
      warnings.push("Remove any remaining bracketed placeholder text before sending this resume.");
    }
    if (boosted) warnings.push(`Deeper rewrite generated by ${boosted.engine}. Review every claim before submission.`);

    const projectedScore = Math.max(projected.score, providedBefore);

    const response: EnhanceResponse = {
      enhancedText: tailored.enhancedText,
      beforeScore: providedBefore,
      projectedScore,
      changes: tailored.changes,
      keywordsWoven: tailored.keywordsWoven,
      engine: tailored.engine,
      warnings,
    };

    return NextResponse.json(response, { headers: { "Cache-Control": "no-store" } });
  } catch (error) {
    if (error instanceof AnalysisRequestError) {
      return NextResponse.json(
        { error: { code: error.code, message: error.message } },
        { status: error.status },
      );
    }
    console.error("ATS enhancement failed:", error);
    return NextResponse.json(
      { error: { code: "INTERNAL_ERROR", message: "We could not build the tailored resume. Please try again." } },
      { status: 500 },
    );
  }
}
